package main

import (
	"fmt"
	"go/ast"
	"sort"
	"strings"
	"unicode"
)

const header = `// Generated by apps/metaboxd/cmd/contractgen from the daemon contract. Do not
// edit: change the daemon, the file is rebuilt by ` + "`make schema-daemon`" + `.
//
// The schemas describe the shape of the response but do not translate it: translation and rejection live in
// the slice adapters.

import { z } from 'zod'
`

// walker translates Go declarations into zod schemas and remembers the order: a schema refers
// to a neighbour, and that one must be declared earlier.
type walker struct {
	src     *sources
	pkg     string
	printed map[string]bool
	order   []string
	bodies  map[string]string
	// enums are the named types with constants met in the contract,
	// keyed by `package.Type`. The key is full: two different types with one name are
	// two enums and must not be merged. The order is kept separately: the map
	// does not store it, and the artifact must be the same from run to run.
	enums      map[string]enumDecl
	enumsOrder []string
}

func generate(root string, roots []rootType) (string, error) {
	pkgs := make([]string, 0, len(roots))
	seen := map[string]bool{}

	for _, item := range roots {
		if !seen[item.pkg] {
			seen[item.pkg] = true
			pkgs = append(pkgs, item.pkg)
		}
	}

	src, err := parseSources(root, pkgs)
	if err != nil {
		return "", err
	}

	w := &walker{src: src, printed: map[string]bool{}, bodies: map[string]string{}, enums: map[string]enumDecl{}}

	for _, item := range roots {
		if err := w.schema(item.pkg, item.name); err != nil {
			return "", err
		}
	}

	return w.render(), nil
}

// schema prints the schema of a type and everything it refers to.
func (w *walker) schema(pkg, name string) error {
	key := pkg + "." + name
	if w.printed[key] {
		return nil
	}

	body, ok := w.src.structOf(key)
	if !ok {
		return fmt.Errorf("type %s is not declared as a struct", key)
	}

	w.printed[key] = true
	previous := w.pkg
	w.pkg = pkg

	fields := w.src.fieldsOf(body)
	lines := make([]string, 0, len(fields))

	for _, item := range fields {
		expr, err := w.expr(item.typ)
		if err != nil {
			return fmt.Errorf("%s.%s: %w", key, item.json, err)
		}

		if item.optional {
			expr += ".optional()"
		}

		if item.doc != "" {
			lines = append(lines, "  /** "+item.doc+" */")
		}

		lines = append(lines, fmt.Sprintf("  %s: %s,", quoteKey(item.json), expr))
	}

	w.pkg = previous

	declared := schemaName(name)
	text := ""

	if doc := w.src.docs[key]; doc != "" {
		text += "/** " + doc + " */\n"
	}

	text += fmt.Sprintf("export const %s = z.object({\n%s\n})\n", declared, strings.Join(lines, "\n"))

	w.bodies[declared] = text
	w.order = append(w.order, declared)

	return nil
}

func (w *walker) expr(node ast.Expr) (string, error) {
	switch typed := node.(type) {
	case *ast.StarExpr:
		return w.expr(typed.X)
	case *ast.ArrayType:
		inner, err := w.expr(typed.Elt)
		if err != nil {
			return "", err
		}

		// []byte arrives as a base64 string, not as a list of numbers.
		if inner == "z.int()" && isByte(typed.Elt) {
			return "z.string()", nil
		}

		return "z.array(" + inner + ")", nil
	case *ast.MapType:
		value, err := w.expr(typed.Value)
		if err != nil {
			return "", err
		}

		return "z.record(z.string(), " + value + ")", nil
	case *ast.SelectorExpr:
		return w.qualified(typed)
	case *ast.InterfaceType:
		return "z.unknown()", nil
	case *ast.Ident:
		return w.named(typed.Name)
	}

	return "", fmt.Errorf("unknown field type")
}

// named separates built-in types from the daemon's own declarations.
func (w *walker) named(name string) (string, error) {
	if builtin, ok := builtins[name]; ok {
		return builtin, nil
	}

	key := w.pkg + "." + name

	if _, ok := w.src.structOf(key); ok {
		if err := w.schema(w.pkg, name); err != nil {
			return "", err
		}

		return schemaName(name), nil
	}

	// The set of values of a named type goes into the schema as a separate constant, and
	// the field stays a string. Parsing must be tolerant: a value the
	// panel does not know is read by the adapter as "unknown", and rejecting the whole
	// response because of one field would cost more. Strictness is needed where it catches
	// a mismatch between the panel and the daemon at compile time, not on the wire.
	if values, ok := w.src.values[key]; ok {
		w.rememberEnum(key, enumDecl{pkg: w.pkg, name: name, values: values})
	}

	// A type not declared as a struct is printed by its base type: `Phase string`
	// stays a string on the wire.
	spec, ok := w.src.decls[key]
	if !ok {
		return "", fmt.Errorf("type %s not found", key)
	}

	return w.expr(spec.Type)
}

// qualified handles types from other packages: own ones are expanded, foreign ones
// are printed by the rule from the table.
func (w *walker) qualified(node *ast.SelectorExpr) (string, error) {
	pkg, ok := node.X.(*ast.Ident)
	if !ok {
		return "", fmt.Errorf("unknown field type")
	}

	qualified := pkg.Name + "." + node.Sel.Name

	if external, ok := externals[qualified]; ok {
		return external, nil
	}

	// The package might not be among the roots: the contract refers to a domain type, and it
	// lies in its own package.
	if err := w.src.readPackage("internal/" + pkg.Name); err != nil {
		return "", err
	}

	for key := range w.src.decls {
		if strings.HasSuffix(key, "/"+pkg.Name+"."+node.Sel.Name) {
			owner := strings.TrimSuffix(key, "."+node.Sel.Name)

			if _, ok := w.src.structOf(key); ok {
				if err := w.schema(owner, node.Sel.Name); err != nil {
					return "", err
				}

				return schemaName(node.Sel.Name), nil
			}

			// Not a struct but an enum or an alias of a base type:
			// printed the same way as one declared in its own package.
			previous := w.pkg
			w.pkg = owner
			expr, err := w.named(node.Sel.Name)
			w.pkg = previous

			return expr, err
		}
	}

	return "", fmt.Errorf("type %s is not described: add a rule to the table", qualified)
}

// enumDecl is an enum as the daemon declared it.
type enumDecl struct {
	pkg    string
	name   string
	values []string
}

// rememberEnum remembers a type once: the contract refers to the same type
// from several places, and one constant is needed.
func (w *walker) rememberEnum(key string, decl enumDecl) {
	if _, ok := w.enums[key]; ok {
		return
	}

	w.enums[key] = decl
	w.enumsOrder = append(w.enumsOrder, key)
}

// enumNames hands out names to constants. Matching names of different types are separated
// by package: `route.Kind` and `events.Kind` would give one `KIND`, and one
// enum would silently displace the other.
func (w *walker) enumNames() map[string]string {
	count := map[string]int{}

	for _, key := range w.enumsOrder {
		count[constantName(w.enums[key].name)]++
	}

	names := make(map[string]string, len(w.enumsOrder))

	for _, key := range w.enumsOrder {
		decl := w.enums[key]
		name := constantName(decl.name)

		if count[name] > 1 {
			name = constantName(packageName(decl.pkg)) + "_" + name
		}

		names[key] = name
	}

	return names
}

// packageName is the last segment of a package path: `internal/route` → `route`.
func packageName(pkg string) string {
	if i := strings.LastIndexByte(pkg, '/'); i >= 0 {
		return pkg[i+1:]
	}

	return pkg
}

func (w *walker) render() string {
	parts := make([]string, 0, len(w.order)+len(w.enumsOrder)+1)
	parts = append(parts, header)

	names := w.enumNames()

	for _, key := range w.enumsOrder {
		parts = append(parts, enumBody(names[key], w.enums[key].values))
	}

	for _, name := range w.order {
		parts = append(parts, w.bodies[name])
	}

	types := make([]string, 0, len(w.order))

	for _, name := range w.order {
		base := strings.TrimSuffix(name, "Schema")
		types = append(types, fmt.Sprintf("export type %sWire = z.infer<typeof %s>", base, name))
	}

	sort.Strings(types)
	parts = append(parts, strings.Join(types, "\n")+"\n")

	return strings.Join(parts, "\n")
}

// enumBody prints the values of a named type as a list: the panel
// types its tables by it and cannot silently diverge from the daemon.
func enumBody(name string, values []string) string {
	quoted := make([]string, 0, len(values))

	for _, value := range values {
		quoted = append(quoted, "  '"+value+"',")
	}

	return fmt.Sprintf("export const %s = [\n%s\n] as const\n", name, strings.Join(quoted, "\n"))
}

// constantName turns a type name into a constant name: ErrorCode → ERROR_CODE.
func constantName(name string) string {
	var out strings.Builder

	for i, r := range name {
		if unicode.IsUpper(r) && i > 0 {
			out.WriteByte('_')
		}

		out.WriteRune(unicode.ToUpper(r))
	}

	return out.String()
}

func isByte(node ast.Expr) bool {
	ident, ok := node.(*ast.Ident)

	return ok && (ident.Name == "byte" || ident.Name == "uint8")
}

func quoteKey(name string) string {
	for _, symbol := range name {
		if !unicode.IsLetter(symbol) && !unicode.IsDigit(symbol) && symbol != '_' {
			return "'" + name + "'"
		}
	}

	return name
}

func schemaName(name string) string {
	runes := []rune(name)
	runes[0] = unicode.ToUpper(runes[0])

	return string(runes) + "Schema"
}
