package main

import (
	"fmt"
	"strings"
)

const fileHeader = `// Generated by tools/schemagen from sing-box-extended %s. Do not edit:
// change the generator, the file is rebuilt by ` + "`make schema`" + `.
//
// The schemas are kept representable for z.toJSONSchema(): the auto-renderer
// of uncovered config nodes is built from them.

import * as z from "zod"

/**
 * The fork version these schemas are built from. The panel compares it with the version
 * of the binary on the device: the forms know exactly the types that were in this version.
 */
export const SCHEMA_FORK_VERSION = "%[1]s"

`

// emit prints the file with the schemas. References inside objects go as getters and
// are resolved on field access, so mutual recursion needs no ordering;
// everything else, arrays, unions, .extend(), is evaluated at declaration,
// and schemaSet.sorted places such schemas after their dependencies.
func emit(
	set *schemaSet,
	root *schema,
	version string,
	gates map[string]map[string]string,
	options []optionGate,
	groups []registryGroup,
) string {
	var b strings.Builder
	fmt.Fprintf(&b, fileHeader, version)
	emitGates(&b, gates, groups)
	emitOptionGates(&b, options)

	for _, named := range set.sorted() {
		fmt.Fprintf(&b, "export const %s = ", named.name)
		named.schema.write(&b, "")
		b.WriteString("\n\n")
	}

	b.WriteString("export const ConfigSchema = ")
	root.write(&b, "")
	b.WriteString("\n\nexport type Config = z.infer<typeof ConfigSchema>\n")

	return b.String()
}
